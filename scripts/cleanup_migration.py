"""Candidate cleanup file migration: preview, bound apply, verify and undo.

No audit DB writes, recursive deletion, directory moves or authorization factory.
Authorization is a supplied controlled decision, not generated by this tool.
Path guards assume a cooperative single writer, not an adversarial filesystem.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path,PurePosixPath
import stat
import zipfile

from cleanup_inventory import digest


def plan_hash(plan):
    return hashlib.sha256(json.dumps(plan,sort_keys=True,ensure_ascii=False,separators=(',',':')).encode('utf-8')).hexdigest()


def root_path(root):
    root=Path(root).absolute()
    if root==Path(root.anchor) or root==Path.home() or not root.is_dir():
        raise ValueError('explicit non-broad existing root required')
    if root.resolve()!=root:
        raise ValueError('redirected root refused')
    return root


def safe(root,relative,allow_pair=False):
    parts=PurePosixPath(relative).parts
    if not parts or PurePosixPath(relative).is_absolute() or '\\' in relative or any(p=='..' or ':' in p for p in parts):
        raise ValueError('unsafe relative target')
    if any(p.rstrip(' .')!=p for p in parts):
        raise ValueError('Windows-normalized alias refused')
    folded=[p.casefold() for p in parts]
    if any(p in {'.git','.agents','.claude'} for p in folded) or folded[-1]=='claude.md' or folded[-1].startswith('cc_'):
        raise ValueError('agent/Git ownership target refused')
    if folded[0] in {'incoming','raw','db','sieving','audit_template','audit_archives'} or len(parts)>1 and folded[1] in {'incoming','raw','db','sieving'}:
        raise ValueError('protected audit target refused')
    path=root.joinpath(*parts)
    for candidate in (path,*path.parents):
        if not candidate.is_relative_to(root):
            break
        try:
            info=candidate.lstat()
        except FileNotFoundError:
            continue
        if stat.S_ISLNK(info.st_mode) or getattr(info,'st_file_attributes',0)&0x400:
            raise ValueError('redirected target refused')
        if candidate!=path and not stat.S_ISDIR(info.st_mode):
            raise ValueError('target parent is not a directory')
        if stat.S_ISREG(info.st_mode) and info.st_nlink>1 and not (allow_pair and candidate==path):
            raise ValueError('hard-linked target refused')
    if not path.resolve().is_relative_to(root):
        raise ValueError('resolved target outside root')
    return path


def identity(path):
    info=path.stat()
    return {'device':info.st_dev,'inode':info.st_ino,'mtime_ns':info.st_mtime_ns,
            'mode':info.st_mode,'attributes':getattr(info,'st_file_attributes',0)}


def check_row(root,row):
    if row.get('hold') or row.get('owner') not in {'codex','shared-or-owner'}:
        raise ValueError('held or foreign-owned row')
    source,dest=safe(root,row['source']),safe(root,row['destination'])
    if source==dest or not source.is_file() or dest.exists():
        raise ValueError('missing source or existing destination')
    if digest(source)!=row['sha256']:
        raise ValueError('source hash changed')
    return source,dest


def preview(root,plan):
    root=root_path(root)
    if plan.get('schema')!='cleanup-file-map-1' or not isinstance(plan.get('files'),list) or not plan['files']:
        raise ValueError('unsupported file map')
    checks=[]
    seen_src,seen_dst=set(),set()
    for row in plan['files']:
        try:
            s,d=row['source'].casefold(),row['destination'].casefold()
            if s in seen_src or d in seen_dst:
                raise ValueError('duplicate source/destination')
            seen_src.add(s);seen_dst.add(d)
            check_row(root,row)
            checks.append({'source':row['source'],'eligible':True})
        except (ValueError,OSError) as error:
            checks.append({'source':row.get('source'),'eligible':False,'reason':str(error)})
    if plan.get('collisions'):
        checks.append({'source':None,'eligible':False,'reason':'map collision records present'})
    return {'mode':'read-only-preview','eligible':sum(c['eligible'] for c in checks),
            'blocked':sum(not c['eligible'] for c in checks),'checks':checks}


def authorize(root,plan,approval):
    if (approval.get('schema')!='cleanup-authorization-1' or approval.get('root')!=str(root)
        or approval.get('plan_sha256')!=plan_hash(plan) or approval.get('allow_apply') is not True
        or not approval.get('owner_decision') or not approval.get('review_decision')):
        raise ValueError('authorization must bind exact root/map and owner/review decisions')


def journal_path(root,path,plan):
    path=Path(path).absolute()
    rel=path.relative_to(root).as_posix()
    safe(root,rel)
    if any(rel in {r['source'],r['destination']} for r in plan['files']):
        raise ValueError('journal overlaps moved file')
    return path


def append(path,event):
    with path.open('rb') as stream:
        stream.seek(-1,os.SEEK_END)
        needs_newline=stream.read(1)!=b'\n'
    with path.open('a',encoding='utf-8',newline='\n') as stream:
        if needs_newline:stream.write('\n')
        stream.write(json.dumps(event,ensure_ascii=False,separators=(',',':'))+'\n')
        stream.flush();os.fsync(stream.fileno())


def header(root,plan,journal):
    lines=journal.read_bytes().splitlines()
    if not lines:raise ValueError('empty journal')
    first=json.loads(lines[0])
    if first.get('kind')!='begin' or first.get('root')!=str(root) or first.get('plan_sha256')!=plan_hash(plan):
        raise ValueError('journal is not bound to root/map')
    seal=first.get('seal')
    if seal!=plan_hash({k:v for k,v in first.items() if k!='seal'}):
        raise ValueError('journal header checksum mismatch')
    authorize(root,plan,first['authorization'])
    if set(first['identities'])!={r['source'] for r in plan['files']}:
        raise ValueError('journal identities differ from file map')
    allowed_dirs={p.relative_to(root).as_posix() for row in plan['files']
                  for p in (root/row['destination']).parents if p!=root and p.is_relative_to(root)}
    if not set(first['new_directories'])<=allowed_dirs:
        raise ValueError('journal directory scope differs from file map')
    events=[first]
    i=1
    while i<len(lines):
        try:
            events.append(json.loads(lines[i]));i+=1
        except (ValueError,UnicodeError):
            recovered=False
            for j in range(i+1,len(lines)):
                try:following=json.loads(lines[j])
                except (ValueError,UnicodeError):continue
                checksum=hashlib.sha256(b'\n'.join(lines[i:j])).hexdigest()
                if following.get('kind')!='torn-tail-recovery' or following.get('suffix_sha256')!=checksum:
                    raise ValueError('invalid committed journal record/recovery checksum')
                events.append(following);i=j+1;recovered=True;break
            if not recovered:
                events.append({'kind':'torn-tail','suffix_sha256':hashlib.sha256(b'\n'.join(lines[i:])).hexdigest()})
                break
    return first,events


def recover_tail(journal,events):
    if events[-1].get('kind')=='torn-tail':
        append(journal,{'kind':'torn-tail-recovery','suffix_sha256':events[-1]['suffix_sha256']})


def state(root,row,witness):
    # POSIX link/unlink interruption may leave our two exact links. Windows
    # native rename is no-replace and does not have this intermediate state.
    source=safe(root,row['source'],allow_pair=True)
    dest=safe(root,row['destination'],allow_pair=True)
    if source.exists() and dest.exists():
        if not os.path.samefile(source,dest) or source.stat().st_nlink!=2:
            raise ValueError('unexpected existing destination')
        actual='linked'
        file=source
    elif source.exists():
        actual='original';file=source
        if file.stat().st_nlink!=1: raise ValueError('unexpected source hardlink')
    elif dest.exists():
        actual='moved';file=dest
        if file.stat().st_nlink!=1: raise ValueError('unexpected destination hardlink')
    else:
        raise ValueError('both source and destination missing')
    if not file.is_file() or digest(file)!=row['sha256'] or identity(file)!=witness:
        raise ValueError('file identity/content changed; refusing overwrite or removal')
    return actual,source,dest


def move_no_replace(source,dest):
    if os.name=='nt':
        os.rename(source,dest)  # Windows refuses an existing destination.
    else:
        os.link(source,dest,follow_symlinks=False)  # exclusive destination
        os.unlink(source)


def apply(root,plan,journal,approval):
    root=root_path(root)
    authorize(root,plan,approval)
    journal=journal_path(root,journal,plan)
    if journal.exists():
        first,events=header(root,plan,journal)
        if first['authorization']!=approval:
            raise ValueError('authorization differs from journal')
        states=[state(root,r,first['identities'][r['source']])[0] for r in plan['files']]
        recover_tail(journal,events)
    else:
        result=preview(root,plan)
        if result['blocked']:
            raise ValueError('preview blocked; no apply allowed')
        first={'kind':'begin','root':str(root),'plan_sha256':plan_hash(plan),
               'authorization':approval,'identities':{r['source']:identity(root/r['source']) for r in plan['files']},
               'new_directories':[]}
        new_dirs=set()
        for row in plan['files']:
            for p in (root/row['destination']).parents:
                if p==root:break
                if not p.exists():new_dirs.add(p.relative_to(root).as_posix())
        first['new_directories']=sorted(new_dirs,key=lambda p:(p.count('/'),p))
        first['seal']=plan_hash(first)
        journal.parent.mkdir(parents=True,exist_ok=True)
        with journal.open('x',encoding='utf-8',newline='\n') as stream:
            stream.write(json.dumps(first,ensure_ascii=False,separators=(',',':'))+'\n')
            stream.flush();os.fsync(stream.fileno())
        states=['original']*len(plan['files'])
    for row,current in zip(plan['files'],states):
        current,source,dest=state(root,row,first['identities'][row['source']])
        if current=='moved':continue
        safe(root,row['destination']) if current=='original' else None
        dest.parent.mkdir(parents=True,exist_ok=True)
        safe(root,row['destination']) if current=='original' else None
        if current=='linked':os.unlink(source)
        else:move_no_replace(source,dest)
        append(journal,{'kind':'moved','source':row['source'],'destination':row['destination']})
    append(journal,{'kind':'apply-complete'})
    return verify(root,plan,journal)


def verify(root,plan,journal):
    root=root_path(root)
    journal=journal_path(root,journal,plan)
    first,events=header(root,plan,journal)
    states=[state(root,r,first['identities'][r['source']])[0] for r in plan['files']]
    incomplete=events[-1].get('kind')=='torn-tail'
    return {'moved':states.count('moved'),'original':states.count('original'),'linked':states.count('linked'),
            'files':len(states),'journal_tail_incomplete':incomplete,
            'complete':all(s=='moved' for s in states) and not incomplete and events[-1].get('kind')=='apply-complete'}


def undo(root,plan,journal):
    root=root_path(root)
    journal=journal_path(root,journal,plan)
    first,events=header(root,plan,journal)
    # Preflight the entire batch so a changed owner file causes no undo writes.
    states=[state(root,r,first['identities'][r['source']])[0] for r in plan['files']]
    recover_tail(journal,events)
    for row,current in reversed(list(zip(plan['files'],states))):
        current,source,dest=state(root,row,first['identities'][row['source']])
        if current=='original':continue
        source.parent.mkdir(parents=True,exist_ok=True)
        if current=='linked':os.unlink(dest)
        else:move_no_replace(dest,source)
        append(journal,{'kind':'undone','source':row['source']})
    retained=[]
    for rel in reversed(first['new_directories']):
        directory=safe(root,rel)
        if directory.exists():
            try:directory.rmdir()  # Only our recorded, empty directories.
            except OSError:retained.append(rel)
    append(journal,{'kind':'undo-complete','retained_directories':retained})
    return {'restored':len(states),'retained_directories':retained}


def load(path):
    if path.suffix.lower()=='.zip':
        with zipfile.ZipFile(path) as z:
            if z.testzip() is not None or len(z.namelist())!=1:
                raise ValueError('invalid map archive')
            return json.loads(z.read(z.namelist()[0]))
    return json.loads(path.read_text(encoding='utf-8'))


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,required=True)
    parser.add_argument('--plan',type=Path,required=True)
    parser.add_argument('--mode',choices=('preview','apply','verify','undo'),default='preview')
    parser.add_argument('--journal',type=Path)
    parser.add_argument('--authorization',type=Path)
    args=parser.parse_args()
    plan=load(args.plan)
    if args.mode=='preview':result=preview(args.root,plan)
    else:
        if not args.journal:parser.error('--journal required')
        if args.mode=='apply':
            if not args.authorization:parser.error('--authorization required')
            result=apply(args.root,plan,args.journal,load(args.authorization))
        elif args.mode=='verify':result=verify(args.root,plan,args.journal)
        else:result=undo(args.root,plan,args.journal)
    print(json.dumps(result,ensure_ascii=True))
    return 1 if result.get('blocked') or args.mode=='verify' and not result['complete'] else 0


if __name__=='__main__':
    raise SystemExit(main())
